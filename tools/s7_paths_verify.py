"""Verify the imported backend file and real portal JSONL through the S7 Wazuh agent.

Uses only the selected personal project's backend volume, then restores the
exact image bytes in finally. Never edits host source or another Docker volume.
"""
from datetime import datetime, timezone
import base64
import hashlib
import json
import time
import urllib.request

from s7_lab import ROOT, LOCAL, PROJECT, agent_id, api, compose, index, run, scrub, wait_for
from s7_verify import agent, http


def main():
    ident = wait_for(agent_id)
    backend = '/var/lib/haedam/backend/haedam_portal/__init__.py'
    wait_for(lambda: api('/syscheck/' + ident + '?search=' + backend).get('total_affected_items', 0) > 0)
    volume = PROJECT + '_s7-backend'
    info = json.loads(run(['docker', 'volume', 'inspect', volume]))[0]
    if info.get('Labels', {}).get('com.docker.compose.project') != PROJECT:
        raise RuntimeError('Not the selected personal project volume.')
    image_id = run(['docker', 'image', 'inspect', PROJECT + '-portal', '--format', '{{.Id}}'])
    original = run(['docker', 'run', '--rm', '--network', 'none', '--entrypoint', 'python', image_id,
        '-c', 'import pathlib,base64; print(base64.b64encode(pathlib.Path("/app/src/haedam_portal/__init__.py").read_bytes()).decode())'])
    expected = hashlib.sha256(base64.b64decode(original)).hexdigest()
    assert agent('import pathlib,hashlib; print(hashlib.sha256(pathlib.Path("' + backend + '").read_bytes()).hexdigest())') == expected
    result = {'project': PROJECT, 'agent_id': ident, 'started_at': datetime.now(timezone.utc).isoformat(), 'checks': {}}

    def write(payload):
        run(['docker', 'run', '--rm', '-i', '--network', 'none', '-v', volume + ':/target',
             '--entrypoint', 'python', 'python:3.12-slim', '-c',
             'import pathlib,base64,sys; pathlib.Path("/target/haedam_portal/__init__.py").write_bytes(base64.b64decode(sys.stdin.read()))'], payload)

    def search(filters):
        result = index('/wazuh-alerts-*/_search', {'size': 10, 'query': {'bool': {'filter': filters}}})
        return result['hits']['hits']

    try:
        for service, path in [('portal', '/app/src/haedam_portal/__init__.py'), ('s7-agent', backend)]:
            output = compose('exec', '-T', service, 'python' if service == 'portal' else 'python3', '-c',
                'try:\n open("' + path + '","ab").close()\n print("writable")\nexcept OSError:\n print("readonly")')
            assert output == 'readonly'
        result['checks']['backend_readonly_in_portal_and_agent'] = True
        changed = base64.b64encode(base64.b64decode(original) + b'\n# Harmless personal Wazuh FIM verification\n').decode()
        changed_hash = hashlib.sha256(base64.b64decode(changed)).hexdigest()
        write(changed)
        hit = wait_for(lambda: next(iter(search([
            {'term': {'agent.id': ident}}, {'term': {'syscheck.path': backend}},
            {'term': {'syscheck.sha256_after': changed_hash}}, {'term': {'rule.id': '550'}},
            {'range': {'timestamp': {'gte': result['started_at']}}}])), None), 120)
        event = hit['_source']
        assert event['syscheck']['sha256_before'] == expected
        result['backend_fim'] = {'alert_id': event['id'], 'rule': event['rule']['id'], 'path': backend,
                                  'sha256_before': expected, 'sha256_after': changed_hash}
        write(original)
        assert agent('import pathlib,hashlib; print(hashlib.sha256(pathlib.Path("' + backend + '").read_bytes()).hexdigest())') == expected
        # Collect an event generated by an actual served HTTP request, never fabricate a Wazuh alert.
        before = agent('import pathlib; print(pathlib.Path("/var/log/haedam-portal/events.jsonl").stat().st_size)')
        assert http()[0] == 200
        rows = json.loads(agent('import pathlib,json,sys; p=pathlib.Path("/var/log/haedam-portal/events.jsonl"); '
            'f=p.open("rb"); f.seek(int(sys.argv[1])); print(json.dumps([json.loads(l) for l in f]))', before))
        served = next(r for r in rows if r['event_type'] == 'web.file_access' and r['details'].get('file_key') == 'index.html')
        hit = wait_for(lambda: next(iter(search([
            {'term': {'agent.id': ident}}, {'term': {'data.event_id': served['event_id']}},
            {'term': {'rule.id': '100711'}}])), None), 120)
        event = hit['_source']
        result['portal_log'] = {'event_id': served['event_id'], 'alert_id': event['id'],
                                'rule': event['rule']['id'], 'file_key': 'index.html', 'http_status': 200}
        result['result'] = 'pass'
    except Exception as exc:
        result.update(result='fail', error=scrub(str(exc)))
        raise
    finally:
        write(original)
        result['restored_backend_sha256'] = agent('import pathlib,hashlib; print(hashlib.sha256(pathlib.Path("' + backend + '").read_bytes()).hexdigest())')
        result['finished_at'] = datetime.now(timezone.utc).isoformat()
        result['source_head'] = run(['git', 'rev-parse', 'HEAD'])
        result['source_sha256'] = {p: hashlib.sha256((ROOT / p).read_bytes()).hexdigest() for p in
            ['compose.s7.yaml', 'infra/wazuh/portal-rules.xml', 'infra/wazuh/agent/ossec.conf', 'tools/s7_paths_verify.py']}
        output = LOCAL / (PROJECT + '-paths.json')
        output.write_text(json.dumps(result, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
        print(json.dumps(result, ensure_ascii=False, indent=2))
        assert result['restored_backend_sha256'] == expected


if __name__ == '__main__':
    try:
        main()
    except Exception as exc:
        raise SystemExit(scrub(str(exc)))
